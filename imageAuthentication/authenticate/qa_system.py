# utils/qa_system.py
import re
from .models import UploadedImage, AIDetection, HumanEditDetection, HeatmapAnalysis, FinalVerdict, QnAHistory, MetadataAnalysis

class ImageQASystem:
    """Complete Q&A system - answers ANY question from database results"""
    
    def __init__(self):
        pass
    
    def _detect_intent(self, question):
        """Detect intent from ANY possible question - priority order matters"""
        q = question.lower().strip()
        
        # ============================================================
        # AI MODEL QUESTIONS (HIGHEST PRIORITY)
        # ============================================================
        
        ai_model_patterns = [
            r'\b(what model|which model|what ai|which ai|ai model|model name)\b',
            r'\b(made by|generated by|created by|produced by)\s+(what|which|what ai|which ai)\b',
            r'\b(what generated|what created|what made)\s+this\b',
            r'\b(model (used|that made|that generated))\b',
            r'\b(what tool|which tool|generated with what)\b',
            r'\b(ai name|ai type|generator|generation tool)\b',
        ]
        if any(re.search(p, q) for p in ai_model_patterns):
            return 'AI_MODEL'
        
        # ============================================================
        # AI DETECTION QUESTIONS (HIGH PRIORITY - BEFORE DATE)
        # ============================================================
        
        # Is it AI? - Check for "AI generated" specifically
        if re.search(r'\b(is this (ai|fake|synthetic)|this ai\?|ai or not|real or ai|is it ai)\b', q):
            return 'WHY_AI'
        
        if re.search(r'\b(ai generated|ai-generated|generated by ai)\b', q):
            return 'WHY_AI'
        
        # What percentage AI?
        if re.search(r'\b(what percentage|how much percent|ai probability|ai chance|likelihood ai)\b', q):
            return 'CONFIDENCE'
        
        # Is it real/authentic?
        real_patterns = [
            r'\b(is this real|this real\?|is it real|real or fake|authentic or not)\b',
            r'\b(can i trust|should i trust|is it trustworthy|is it genuine|is it legitimate)\b',
            r'\b(is it authentic|this authentic|original or fake)\b',
        ]
        if any(re.search(p, q) for p in real_patterns):
            return 'TRUST'
        
        # ============================================================
        # METADATA INTENTS
        # ============================================================
        
        # Camera/Device
        camera_patterns = [
            r'\b(camera|device|make|model|phone|smartphone|brand|manufacturer)\b',
            r'\b(what camera|which camera|what phone|what device)\b',
            r'\b(taken with|shot with|captured with|photo with)\b',
        ]
        if any(re.search(p, q) for p in camera_patterns):
            if not re.search(r'\b(ai|generated)\b', q):
                return 'METADATA_CAMERA'
        
        # Software/Editor
        software_patterns = [
            r'\b(software|editor|tool|app|application|program)\b',
            r'\b(photoshop|lightroom|gimp|edited with|created with)\b',
            r'\b(what software|which software|what editor)\b',
        ]
        if any(re.search(p, q) for p in software_patterns):
            return 'METADATA_SOFTWARE'
        
        # Date/Time - but NOT if it's asking about AI generation
        if not re.search(r'\b(ai generated|ai-generated|generated by ai|is this ai)\b', q):
            date_patterns = [
                r'\b(date|when|time|timestamp|taken|captured|shot|created|generated|modified|uploaded)\b',
                r'\b(what date|what time|what year|when was)\b',
            ]
            if any(re.search(p, q) for p in date_patterns):
                return 'METADATA_DATE'
        
        # GPS/Location
        if re.search(r'\b(gps|coordinates|latitude|longitude|where (was|is) it (taken|captured|shot))\b', q):
            return 'METADATA_GPS'
        
        # Camera Settings
        settings_patterns = [
            r'\b(settings|exif|exposure|shutter speed|aperture|f-stop|iso|focal length|resolution|dimension)\b',
            r'\b(camera settings|exif data)\b',
        ]
        if any(re.search(p, q) for p in settings_patterns):
            return 'METADATA_SETTINGS'
        
        # AI Tool Detection
        aitool_patterns = [
            r'\b(ai tool|generation tool|tool used)\b',
            r'\b(midjourney|dalle|stable diffusion|chatgpt|firefly|bing image|leonardo|playground|copilot|gemini|claude)\b',
            r'\b(what tool|which tool|generated with what|what generated this)\b',
        ]
        if any(re.search(p, q) for p in aitool_patterns):
            return 'METADATA_AITOOL'
        
        # C2PA/Integrity
        if re.search(r'\b(c2pa|integrity|signed|certificate|authenticity|tampered|original|provenance|content credentials)\b', q):
            return 'METADATA_INTEGRITY'
        
        # General metadata
        if re.search(r'\b(metadata|exif|file info|image info|details|information about|tell me about)\b', q):
            return 'METADATA_GENERAL'
        
        # ============================================================
        # IMAGE ANALYSIS INTENTS
        # ============================================================
        
        # Where is it edited?
        if re.search(r'\bwhere\s+(is|was|exactly)\s+(it\s+)?(edited|manipulat|modified|changed|altered)\b', q):
            return 'WHERE'
        
        if q in ['where?', 'where exactly?', 'which part?', 'location?', 'what area?', 'show me where', 'edit location?']:
            return 'WHERE'
        
        # How is it edited?
        if re.search(r'\bhow\s+(is|was|did)\s+(it\s+)?(edited|manipulat|modified|changed)\b', q):
            return 'HOW_EDITED'
        
        # Combined how and where
        if re.search(r'\bhow.*and where|where.*and how\b', q):
            return 'HOW_AND_WHERE'
        
        # General editing detection
        if re.search(r'\b(edited|manipulated|modified|altered|tampered|photoshopped|retouched)\b', q):
            if 'where' not in q and 'how' not in q:
                return 'WHY_EDITED'
        
        # What was edited?
        if re.search(r'\bwhat.*(edited|changed|modified|manipulated|done|altered)\b', q):
            return 'WHAT_EDITED'
        
        # How much was edited?
        if re.search(r'\b(how much|percentage|percent|portion|amount|area)\s+edited\b', q):
            return 'HOW_MUCH'
        
        # Confidence
        if re.search(r'\b(confident|confidence|sure|certain|how sure|how confident|reliable|accurate|trust score|probability)\b', q):
            return 'CONFIDENCE'
        
        # Severity
        if re.search(r'\b(severe|severity|bad|heavily|intense|serious|how bad|how severe|degree|extent|level)\b', q):
            return 'SEVERITY'
        
        # Verdict
        if re.search(r'\b(verdict|result|conclusion|decision|finding|what.*say|overall|final result|what is the verdict)\b', q):
            return 'VERDICT'
        
        # Comparison
        if re.search(r'\b(compare|comparison|difference|versus|vs|between|contrast)\b', q):
            return 'COMPARE'
        
        # Explanation
        if re.search(r'\b(explain|describe|elaborate|clarify|tell me about|what does this mean|how does this work)\b', q):
            return 'EXPLANATION'
        
        # ============================================================
        # FILE & UPLOAD INFO
        # ============================================================
        
        if re.search(r'\b(filename|file name|file size|size|format|type|dimensions|resolution|megapixel)\b', q):
            return 'FILE_INFO'
        
        if re.search(r'\b(uploaded by|who uploaded|owner|creator|author|who submitted|uploader)\b', q):
            return 'UPLOAD_INFO'
        
        # ============================================================
        # HEATMAP & SCORES
        # ============================================================
        
        if re.search(r'\b(heatmap|heat map|hotspot|hot spot|red area|red zone|color map|manipulation map)\b', q):
            return 'HEATMAP'
        
        if re.search(r'\b(score|rating|value|metric|edit score|manipulation score|detection score|confidence score)\b', q):
            return 'SCORES'
        
        # ============================================================
        # RECOMMENDATIONS
        # ============================================================
        
        if re.search(r'\b(recommend|suggest|advice|opinion|what should i|should i use|use this|can i use|is it safe)\b', q):
            return 'RECOMMEND'
        
        # ============================================================
        # GENERAL KNOWLEDGE QUESTIONS
        # ============================================================
        
        if re.search(r'\b(what is|what are|define|meaning of|explain)\s+(c2pa|exif|metadata|heatmap)\b', q):
            return 'EXPLANATION'
        
        # ============================================================
        # PERSONAL & GREETINGS
        # ============================================================
        
        greetings = ['hello', 'hi', 'hey', 'greetings', 'good morning', 'good afternoon', 'good evening', 'howdy', 'sup', 'yo']
        if q.strip() in greetings:
            return 'GREETING'
        
        personal_patterns = [
            r'\b(i love|love you|you are (great|awesome|amazing|smart|intelligent))\b',
            r'\b(how are you|how do you do|how\'s it going)\b',
            r'\b(what is your name|who are you|your name|who made you)\b',
            r'\b(thank you|thanks|appreciate|good job)\b',
            r'\b(sorry|my fault|i apologize)\b',
            r'\b(what can you do|help me|capabilities|features)\b',
            r'\b(are you (human|person|real|alive|conscious))\b',
            r'\b(tell me a joke|make me laugh|say something funny)\b',
        ]
        if any(re.search(p, q) for p in personal_patterns):
            return 'PERSONAL'
        
        # ============================================================
        # INVALID & NONSENSE
        # ============================================================
        
        if len(q) < 4:
            return 'INVALID'
        
        common_names = ['alex', 'john', 'mary', 'peter', 'paul', 'james', 'robert', 'michael', 'david', 'william', 'sarah', 'lisa', 'jennifer', 'mwakenja', 'elvis', 'obama', 'trump', 'biden']
        if any(name in q for name in common_names):
            if not any(word in q for word in ['image', 'photo', 'picture', 'edit', 'ai', 'detect']):
                return 'NONSENSE'
        
        # ============================================================
        # DEFAULT
        # ============================================================
        
        if any(word in q for word in ['image', 'photo', 'picture', 'this', 'picture']):
            return 'GENERAL'
        
        return 'OFF_TOPIC'
    
    def get_image_analysis_data(self, image_id):
        """Fetch ALL analysis results from database"""
        try:
            image = UploadedImage.objects.get(id=image_id)
            ai = AIDetection.objects.filter(image=image).first()
            human = HumanEditDetection.objects.filter(image=image).first()
            heatmap = HeatmapAnalysis.objects.filter(image=image).first()
            verdict = FinalVerdict.objects.filter(image=image).first()
            metadata = MetadataAnalysis.objects.filter(image=image).first()
            
            missing = []
            if not ai: missing.append("AI detection")
            if not human: missing.append("human edit detection")
            if not heatmap: missing.append("heatmap analysis")
            if not verdict: missing.append("final verdict")
            
            if missing:
                return None, f"Analysis incomplete. Missing: {', '.join(missing)}. Run analysis first."
            
            # Parse metadata verdict for AI tool info
            metadata_verdict = metadata.verdict if metadata else ""
            ai_tool_from_verdict = ""
            
            if metadata_verdict:
                # First check for common AI tool names
                ai_tools = ['midjourney', 'dalle', 'stable diffusion', 'chatgpt', 'firefly', 
                           'leonardo', 'playground', 'bing', 'copilot', 'gemini', 'claude', 
                           'imagen', 'craiyon', 'wombo', 'nightcafe', 'starryai']
                for tool in ai_tools:
                    if tool in metadata_verdict.lower():
                        ai_tool_from_verdict = tool.title()
                        break
                
                # If not found, try regex patterns
                if not ai_tool_from_verdict:
                    ai_tool_patterns = [
                        r'AI-generated using ([^)]+)',
                        r'generated with ([^)]+)',
                        r'created by ([^)]+)',
                        r'using ([^)]+)',
                        r'midjourney|dalle|stable diffusion|chatgpt|firefly|leonardo|playground|bing',
                    ]
                    for pattern in ai_tool_patterns:
                        match = re.search(pattern, metadata_verdict.lower())
                        if match:
                            if '|' in pattern:
                                ai_tool_from_verdict = match.group(0).title() if match.group(0) else pattern.split('|')[0].title()
                            else:
                                ai_tool_from_verdict = match.group(1).strip().title() if match.groups() else match.group(0).title()
                            break
            
            return {
                'image': image,
                'ai': {'label': ai.label, 'confidence': ai.confidence},
                'human_edit': {'score': human.detection_score, 'is_edited': human.detection_score > 0.35},
                'heatmap': {
                    'primary': heatmap.primary_region,
                    'secondary': heatmap.secondary_region,
                    'max_score': heatmap.max_edit_score,
                    'avg_score': heatmap.avg_edit_score,
                    'edited_percent': heatmap.edited_percentage,
                    'severity': heatmap.severity_level,
                    'zones': heatmap.edit_zones_count,
                },
                'verdict': verdict.verdict,
                'overall_confidence': verdict.confidence_score if verdict else 0,
                'metadata': {
                    'camera_make': metadata.camera_make,
                    'camera_model': metadata.camera_model,
                    'software': metadata.software,
                    'date_original': metadata.date_original,
                    'modify_date': metadata.modify_date,
                    'gps_lat': metadata.gps_latitude,
                    'gps_lon': metadata.gps_longitude,
                    'exposure': metadata.exposure_time,
                    'f_number': metadata.f_number,
                    'iso': metadata.iso,
                    'focal_length': metadata.focal_length,
                    'width': metadata.resolution_width,
                    'height': metadata.resolution_height,
                    'c2pa': metadata.c2pa_present,
                    'ai_tool': metadata.ai_tool or ai_tool_from_verdict,
                    'verdict_text': metadata.verdict,
                }
            }, None
        except Exception as e:
            return None, f"Error: {str(e)}"
    
    def get_answer(self, image_id, question):
        """Main entry - answers 80+ question types"""
        
        intent = self._detect_intent(question)
        
        # Handle personal/greeting first
        if intent == 'GREETING':
            return self._greeting(), False
        if intent == 'PERSONAL':
            return self._personal_response(question), False
        if intent == 'INVALID':
            return self._invalid(), False
        if intent == 'NONSENSE':
            return self._nonsense(), False
        
        # Get analysis data
        data, error = self.get_image_analysis_data(image_id)
        if error:
            return error, False
        
        # Check cache
        cached = QnAHistory.objects.filter(image_id=image_id, question__iexact=question).first()
        if cached:
            return cached.answer, True
        
        # Route to appropriate handler
        handlers = {
            'AI_MODEL': self._ai_model,
            'METADATA_CAMERA': self._camera,
            'METADATA_SOFTWARE': self._software,
            'METADATA_DATE': self._date,
            'METADATA_GPS': self._gps,
            'METADATA_SETTINGS': self._settings,
            'METADATA_AITOOL': self._aitool,
            'METADATA_INTEGRITY': self._integrity,
            'METADATA_GENERAL': self._metadata_general,
            'WHY_AI': self._is_ai,
            'TRUST': self._trust,
            'WHY_EDITED': self._edited,
            'WHERE': self._where,
            'HOW_EDITED': self._how_edited,
            'HOW_AND_WHERE': self._how_and_where,
            'WHAT_EDITED': self._what_edited,
            'HOW_MUCH': self._how_much,
            'CONFIDENCE': self._confidence,
            'SEVERITY': self._severity,
            'VERDICT': self._verdict,
            'COMPARE': self._compare,
            'EXPLANATION': self._explanation,
            'FILE_INFO': self._file_info,
            'UPLOAD_INFO': self._upload_info,
            'HEATMAP': self._heatmap_info,
            'SCORES': self._scores,
            'RECOMMEND': self._recommend,
            'GENERAL': self._general,
            'OFF_TOPIC': self._off_topic,
        }
        
        handler = handlers.get(intent, self._general)
        answer = handler(data, question)
        
        # Save to cache
        QnAHistory.objects.create(
            image_id=image_id, question=question, answer=answer,
            question_type=intent, used_ai_confidence=data['ai']['confidence'],
            used_human_score=data['human_edit']['score'],
            used_primary_region=data['heatmap']['primary'],
            used_verdict=data['verdict'], was_from_cache=False
        )
        
        return answer, False
    
