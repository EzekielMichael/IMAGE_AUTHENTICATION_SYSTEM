    def _confidence(self, data, q=None):
        h = data['human_edit']
        overall_conf = data.get('overall_confidence', 0)
        if data['verdict'] == "AUTHENTIC IMAGE":
            base = f"I'm {overall_conf:.1f}% confident this image is authentic/real."
        elif "AI Generated" in data['verdict']:
            base = f"I'm {overall_conf:.1f}% confident this image is AI-generated."
        elif "Human Edited" in data['verdict']:
            base = f"I'm {overall_conf:.1f}% confident this image has been human-edited."
        else:
            base = f"I'm {overall_conf:.1f}% confident in this verdict."
        if h['is_edited']:
            base += f" Additionally, human editing detected with {h['score']:.2f} confidence."
        return base
    
    def _severity(self, data, q=None):
        hm = data['heatmap']
